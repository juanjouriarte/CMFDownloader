def submit(db,job='administradores'):
    with db() as s:
        row=api.enqueue(s,job,'editor');s.commit();return row


def test_duplicate_enqueue_and_running_job_conflict(db):
    submit(db,'mf_daily_nav')
    with db() as s,pytest.raises(HTTPException) as caught:api.enqueue(s,'fm_nnm_daily','editor')
    assert caught.value.status_code==409
    with control.job_lock('administradores'):
        with db() as s,pytest.raises(HTTPException) as caught:api.enqueue(s,'administradores','editor')
        assert caught.value.status_code==409
        with pytest.raises(JobBusy):
            with control.job_lock('administradores'):pass


def test_concurrent_clicks_create_one_request(db):
    barrier=threading.Barrier(2)
    def send(_):
        barrier.wait()
        try:return submit(db)['id']
        except HTTPException as e:return e.status_code
    with ThreadPoolExecutor(max_workers=2) as pool:results=list(pool.map(send,range(2)))
    assert 409 in results
    with db() as s:assert s.execute(text('SELECT count(*) FROM job_requests')).scalar()==1


def test_worker_execution_tracking_partial_and_history(db,client):
    row=submit(db,'mf_daily_nav');events=[]
    def fn(name,errors=0):
        def execute():
            events.append(name)
            return scheduler._run_tracked(name,lambda:DownloadResult(rows_upserted=7,errors=errors))
        return execute
    runner.process_next({'mf_daily_nav':fn('mf_daily_nav',1),'mf_rentabilidad':fn('mf_rentabilidad')})
    assert events==['mf_daily_nav','mf_rentabilidad']
    with db() as s:
        item=s.execute(text('SELECT * FROM job_requests')).mappings().one()
        assert item['status']=='partial' and item['completed']==2 and item['error_count']==1
        runs=s.execute(text('SELECT * FROM job_runs ORDER BY id')).mappings().all()
        assert [r['status'] for r in runs]==['partial','success']
        assert all(r['request_id']==row['id'] for r in runs)
    auth={'Authorization':'Bearer test-key'}
    response=client.get('/job-runner/jobs/mf_daily_nav/runs',headers=auth)
    assert response.status_code==200 and response.json()[0]['requested_by']=='editor'
    assert client.get('/job-runner/jobs',headers=auth).json()['worker']['online']


def test_only_one_consumer_can_execute(db):
    submit(db);started=threading.Event();release=threading.Event();calls=[]
    def work():
        calls.append(1);started.set();assert release.wait(10)
    with ThreadPoolExecutor(max_workers=2) as pool:
        first=pool.submit(runner.process_next,{'administradores':work})
        assert started.wait(5)
        second=pool.submit(runner.process_next,{'administradores':work})
        second.result(timeout=5);release.set();first.result(timeout=5)
    assert len(calls)==1


def test_offline_cancel_and_interrupted_recovery(db,client):
    row=submit(db)
    auth={'Authorization':'Bearer test-key'}
    assert client.delete(f"/job-runner/requests/{row['id']}",headers=auth).json()['status']=='cancelled'
    assert client.delete(f"/job-runner/requests/{row['id']}",headers=auth).status_code==409
    row=submit(db)
    with db() as s:
        s.execute(text("UPDATE job_requests SET status='running' WHERE id=:id"),row)
        s.execute(text("INSERT INTO job_runs(job_id,started_at,status,request_id) VALUES('administradores',now(),'running',:id)"),row)
        s.commit()
    runner.process_next({})
    with db() as s:
        assert s.execute(text('SELECT status FROM job_requests WHERE id=:id'),row).scalar()=='interrupted'
        assert s.execute(text('SELECT status FROM job_runs')).scalar()=='interrupted'
        s.execute(text("UPDATE job_runner_heartbeat SET seen_at=now()-interval '2 minutes'"));s.commit()
    with db() as s,pytest.raises(HTTPException) as caught:api.enqueue(s,'administradores','editor')
    assert caught.value.status_code==503
