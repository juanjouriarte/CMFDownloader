import os
from datetime import date
from pathlib import Path
from types import SimpleNamespace

import pytest
from sqlalchemy import text
from sqlalchemy.orm import Session

from src.etl.mutualFunds.loaders import tac as loader


def source(monkeypatch,period=20260731):
    values=[period,'AGF','Fund',1,'CLP','A','','','','',1,2,3,6,'','','','']
    sheet=SimpleNamespace(nrows=5,cell_value=lambda r,c:values[c])
    monkeypatch.setattr(loader.xlrd,'open_workbook',lambda *a,**k:SimpleNamespace(sheet_by_index=lambda _:sheet))
    monkeypatch.setattr(loader,'_build_run_fondo_lookup',lambda:{('FUND','AGF'):'1'})


def test_tac_rejects_wrong_month_before_opening_write_session(monkeypatch):
    source(monkeypatch,20260831)
    monkeypatch.setattr(loader,'SessionLocal',lambda:pytest.fail('must reject before any delete'))
    with pytest.raises(ValueError,match='outside 2026-07'):
        loader.load_tac(Path('fixture.xls'),2026,7)


def test_tac_reload_replaces_month_end_duplicates_and_preserves_other_months(monkeypatch):
    if os.getenv('RUN_WORKSPACE_DB_TESTS')!='1':
        pytest.skip('Enable local PostgreSQL rollback fixture with RUN_WORKSPACE_DB_TESTS=1')
    from src.db.engine import engine
    assert engine.url.host in ('localhost','127.0.0.1')
    source(monkeypatch)
    with engine.connect() as conn:
        transaction=conn.begin()
        try:
            conn.execute(text('CREATE TEMP TABLE tac (LIKE public.tac INCLUDING ALL) ON COMMIT DROP'))
            conn.execute(text('ALTER TABLE pg_temp.tac ALTER COLUMN id DROP DEFAULT'))
            conn.execute(text('ALTER TABLE pg_temp.tac ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY'))
            conn.execute(text("INSERT INTO pg_temp.tac(periodo,run_fondo,serie) VALUES ('2026-06-30','1','A'),('2026-07-31','1','A'),('2026-07-31','1','A'),('2026-08-31','1','A')"))
            monkeypatch.setattr(loader,'SessionLocal',lambda:Session(bind=conn,join_transaction_mode='create_savepoint'))
            for _ in range(2):
                assert loader.load_tac(Path('fixture.xls'),2026,7)==1
                counts=conn.execute(text('SELECT periodo,count(*) FROM pg_temp.tac GROUP BY periodo ORDER BY periodo')).all()
                assert counts==[(date(2026,6,30),1),(date(2026,7,31),1),(date(2026,8,31),1)]
        finally:
            transaction.rollback()
